    // How the examples are written. Notes are named by letter and octave as in "c5": c4 is middle C, c5 the C above it. More
    // attributes on a note are given as MEI, with single quotes: "accid='s'", "xml:id='a'".

    /// <summary>The metronome's quarter note, as Verovio's import of MusicXML writes it: ♩.</summary>
    private const string Crotchet = """<rend glyph.auth="smufl">&#xECA5;</rend>""";

    /// <summary>The segno, over the start of a bar.</summary>
    private const string Segno = """<repeatMark tstamp="1" staff="1" place="above" func="segno"/>""";

    /// <summary>Plain notes of one length: <c>Notes("4", "c5 d5 e5")</c> is three quarter notes.</summary>
    private static string Notes(string dur, string pitches) =>
        string.Concat(pitches.Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(pitch => Note(pitch, dur)));

    /// <summary>One note, with any more attributes: <c>Note("f5", "4", "accid='s'")</c>.</summary>
    private static string Note(string pitch, string dur, string more = "")
    {
        var (pname, oct, extra) = (pitch[..^1], pitch[^1], Extra(more));
        return $"""<note pname="{pname}" oct="{oct}" dur="{dur}"{extra}/>""";
    }

    /// <summary>A note with its name, or its count, printed under it as a lyric: <c>Named("e4", "4", "E")</c>.</summary>
    private static string Named(string pitch, string dur, string name, string more = "")
    {
        var (pname, oct, extra) = (pitch[..^1], pitch[^1], Extra(more));
        return $"""<note pname="{pname}" oct="{oct}" dur="{dur}"{extra}><verse n="1"><syl>{name}</syl></verse></note>""";
    }

    /// <summary>Notes sounded together on one stem: <c>Chord("2", "c4 e4 g4")</c>.</summary>
    private static string Chord(string dur, string pitches, string more = "")
    {
        var (heads, extra) = (string.Concat(pitches.Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(Head)), Extra(more));
        return $"""<chord dur="{dur}"{extra}>{heads}</chord>""";
    }

    private static string Head(string pitch)
    {
        var (pname, oct) = (pitch[..^1], pitch[^1]);
        return $"""<note pname="{pname}" oct="{oct}"/>""";
    }

    /// <summary>A bar of music on one staff, for <see cref="GlossaryMusic.Section"/>: its notes, its control events, and the bar's own attributes ("right='end'").</summary>
    private static string Bar(int n, string notes, string controls = "", string attrs = "")
    {
        var extra = Extra(attrs);
        return $"""<measure n="{n}"{extra}><staff n="1"><layer n="1">{notes}</layer></staff>{controls}</measure>""";
    }

    /// <summary>A dynamic under the staff at beat <paramref name="at"/>: <c>Dynam("mf", "1")</c>.</summary>
    private static string Dynam(string text, string at, int staff = 1) => $"""<dynam tstamp="{at}" staff="{staff}">{text}</dynam>""";

    /// <summary>Words in italics over or under the staff at beat <paramref name="at"/>: <c>Dir("dolce", "1", "below")</c>.</summary>
    private static string Dir(string words, string at, string place, int staff = 1) =>
        $"""<dir tstamp="{at}" staff="{staff}" place="{place}">{words}</dir>""";

    /// <summary>Words ending at the bar's end, over the staff, the way "Fine" and "D.C. al Fine" are printed.</summary>
    private static string AtEnd(string words, string at = "5") => $"""<dir tstamp="{at}" staff="1" place="above"><rend halign="right">{words}</rend></dir>""";

    /// <summary>The coda sign, over the staff at beat <paramref name="at"/>.</summary>
    private static string CodaSign(string at) => $"""<repeatMark tstamp="{at}" staff="1" place="above" func="coda"/>""";

    // Words over the staff sit just clear of the notes under them, so the examples keep those notes inside the staff: a word and
    // the words beside it then share a line. (Verovio lines up directions by @vgrp, but not a tempo with a direction.)

    /// <summary>The music's tempo, in bold over the first beat, at <paramref name="bpm"/> quarter notes a minute.</summary>
    private static string Tempo(string words, int bpm) =>
        $"""<tempo tstamp="1" staff="1" mm="{bpm}" mm.unit="4" midi.bpm="{bpm}">{words}</tempo>""";

    /// <summary>Words in italics on the tempo's line, at beat <paramref name="at"/> (clear of the tempo): "Allegro maestoso".</summary>
    private static string Beside(string words, string at) => $"""<dir tstamp="{at}" staff="1" place="above">{words}</dir>""";

    /// <summary>
    /// A tempo word heading the music, in bold over the first beat, with its metronome mark beside it at beat <paramref name="at"/>
    /// (clear of the word). The word is a direction and the mark the tempo, as many imported pieces have them.
    /// </summary>
    private static string Heading(string word, int bpm, string at) =>
        $"""<dir tstamp="1" staff="1" place="above"><rend fontstyle="normal" fontweight="bold">{word}</rend></dir>"""
        + $"""<tempo tstamp="{at}" staff="1" mm="{bpm}" mm.unit="4" midi.bpm="{bpm}">{Crotchet} = {bpm}</tempo>""";

    private static string Extra(string attrs) => attrs.Length == 0 ? "" : " " + attrs;
